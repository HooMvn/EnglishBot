"""
Handlers for the "extra" exercise types: sentence scramble, fill-in-the-blank,
vocabulary match, translation, and reading-with-summary.

Scored exercise types (scramble, fill-in-the-blank, vocabulary) share a
common completion helper that saves progress and shows a result message.
Open-ended types (translation, summary) use FSM states to capture the
user's free-text reply and don't record a numeric score.
"""

import logging
import random
from typing import List

from aiogram import F, Router
from aiogram.fsm.context import FSMContext
from aiogram.types import CallbackQuery, InlineKeyboardButton, Message
from aiogram.utils.keyboard import InlineKeyboardBuilder

from bot import bot, db
from keyboards import get_back_to_main_keyboard
from states import ExerciseState

router = Router()
logger = logging.getLogger(__name__)


# ----------------------------------------------------------------------
# Shared helpers
# ----------------------------------------------------------------------

async def handle_exercise_completion(
    callback: CallbackQuery, state: FSMContext, exercise_id: int
) -> None:
    """
    Finalize a scored extra exercise.

    Reads the score/total that the calling handler stashed in FSM data
    (`current_score`, `current_total`), saves it to the database, shows a
    success message, and clears the FSM state.
    """
    try:
        data = await state.get_data()
        score = data.get("current_score", 0)
        total = data.get("current_total", 1)

        await db.save_user_progress(callback.from_user.id, exercise_id, score, total)

        await callback.message.answer(
            f"🎉 تمرین تمام شد! نتیجه: {score} از {total}",
            reply_markup=get_back_to_main_keyboard(),
        )
    except Exception as e:
        logger.error(f"Error completing exercise {exercise_id}: {e}")
    finally:
        await state.clear()


def _build_feedback_keyboard(
    options: List[str], chosen_index: int, correct_index: int
) -> InlineKeyboardBuilder:
    """
    Build a read-only feedback keyboard marking the chosen and correct
    options with ✅/❌, with 'noop' callback data for every button.
    """
    builder = InlineKeyboardBuilder()
    for idx, option in enumerate(options):
        is_chosen = idx == chosen_index
        is_correct_option = idx == correct_index
        if is_chosen and is_correct_option:
            label = f"✅ {option}"
        elif is_chosen and not is_correct_option:
            label = f"❌ {option}"
        elif is_correct_option:
            label = f"✅ {option}"
        else:
            label = option
        builder.row(InlineKeyboardButton(text=label, callback_data="noop"))
    return builder


@router.callback_query(F.data == "noop")
async def handle_noop(callback: CallbackQuery) -> None:
    """Swallow taps on already-answered feedback buttons."""
    await callback.answer()


# ----------------------------------------------------------------------
# Scramble (sentence ordering)
# ----------------------------------------------------------------------

def _generate_scramble_options(
    words: List[str], correct_sentence: str, num_options: int = 3
) -> List[str]:
    """
    Build a shuffled list of sentence options, one of which is the correct
    ordering of `words`. Distractors are generated by re-shuffling the same
    words; if not enough distinct distractors can be produced, the list may
    end up shorter than `num_options`.
    """
    options = {correct_sentence}
    attempts = 0
    while len(options) < num_options and attempts < 20:
        shuffled = words[:]
        random.shuffle(shuffled)
        candidate = " ".join(shuffled)
        if candidate.strip():
            options.add(candidate)
        attempts += 1

    options_list = list(options)
    random.shuffle(options_list)
    return options_list


@router.callback_query(F.data.startswith("start_scramble:"))
async def handle_start_scramble(callback: CallbackQuery, state: FSMContext) -> None:
    """Present a scrambled sentence and multiple-choice reordering options."""
    try:
        exercise_id = int(callback.data.split(":")[1])
        exercise = await db.get_exercise(exercise_id)

        if not exercise:
            await callback.answer("⚠️ تمرین یافت نشد.", show_alert=True)
            return

        content = exercise.get("content")
        if (
            not isinstance(content, dict)
            or "words" not in content
            or "correct" not in content
        ):
            await callback.message.answer(
                "⚠️ این تمرین به درستی تنظیم نشده است.",
                reply_markup=get_back_to_main_keyboard(),
            )
            await callback.answer()
            return

        words = content["words"]
        correct_sentence = content["correct"]

        options = _generate_scramble_options(words, correct_sentence)
        correct_index = options.index(correct_sentence)

        # Persist the generated options so the answer handler validates
        # against the exact same choices the user was shown.
        await state.update_data(
            scramble_exercise_id=exercise_id,
            scramble_options=options,
            scramble_correct_index=correct_index,
        )

        builder = InlineKeyboardBuilder()
        for idx, option in enumerate(options):
            builder.row(
                InlineKeyboardButton(
                    text=option, callback_data=f"scramble_answer:{exercise_id}:{idx}"
                )
            )

        await callback.message.answer(
            "🔀 این کلمات را مرتب کن:\n\n" + " / ".join(words),
            reply_markup=builder.as_markup(),
        )
        await callback.answer()
    except Exception as e:
        logger.error(f"Error starting scramble exercise '{callback.data}': {e}")
        await callback.answer("⚠️ خطایی رخ داد.", show_alert=True)


@router.callback_query(F.data.startswith("scramble_answer:"))
async def handle_scramble_answer(callback: CallbackQuery, state: FSMContext) -> None:
    """Grade the chosen sentence ordering and finish the exercise."""
    try:
        _, exercise_id_raw, opt_index_raw = callback.data.split(":")
        exercise_id = int(exercise_id_raw)
        opt_index = int(opt_index_raw)

        data = await state.get_data()
        if data.get("scramble_exercise_id") != exercise_id:
            await callback.answer(
                "⚠️ این تمرین دیگر معتبر نیست. دوباره شروع کن.", show_alert=True
            )
            return

        options = data.get("scramble_options", [])
        correct_index = data.get("scramble_correct_index")
        is_correct = opt_index == correct_index

        builder = _build_feedback_keyboard(options, opt_index, correct_index)
        try:
            await callback.message.edit_reply_markup(reply_markup=builder.as_markup())
        except Exception:
            pass

        await state.update_data(current_score=1 if is_correct else 0, current_total=1)
        await handle_exercise_completion(callback, state, exercise_id)
        await callback.answer()
    except Exception as e:
        logger.error(f"Error grading scramble answer '{callback.data}': {e}")
        await callback.answer("⚠️ خطایی رخ داد.", show_alert=True)


