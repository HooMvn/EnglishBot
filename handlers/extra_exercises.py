@router.callback_query(F.data.startswith("start_translation:"))
async def handle_start_translation(callback: CallbackQuery, state: FSMContext) -> None:
    """Prompt the user to translate a sentence and await their free-text reply."""
    try:
        exercise_id = int(callback.data.split(":")[1])
        exercise = await db.get_exercise(exercise_id)

        if not exercise:
            await callback.answer("⚠️ تمرین یافت نشد.", show_alert=True)
            return

        content = exercise.get("content")
        if not isinstance(content, dict) or "source" not in content:
            await callback.message.answer(
                "⚠️ این تمرین به درستی تنظیم نشده است.",
                reply_markup=get_back_to_main_keyboard(),
            )
            await callback.answer()
            return

        await state.set_state(ExerciseState.waiting_for_translation)
        await state.update_data(translation_exercise_id=exercise_id)

        await callback.message.answer(
            f"🔄 این جمله را ترجمه کن:\n\n<b>{content['source']}</b>\n\n"
            "✍️ ترجمه خودت را بفرست:"
        )
        await callback.answer()
    except Exception as e:
        logger.error(f"Error starting translation exercise '{callback.data}': {e}")
        await callback.answer("⚠️ خطایی رخ داد.", show_alert=True)


@router.message(ExerciseState.waiting_for_translation, F.text)
async def handle_translation_reply(message: Message, state: FSMContext) -> None:
    """Receive the user's translation attempt and show the suggested one."""
    try:
        data = await state.get_data()
        exercise_id = data.get("translation_exercise_id")
        exercise = await db.get_exercise(exercise_id) if exercise_id else None
        content = exercise.get("content") if exercise else None

        if not isinstance(content, dict):
            await message.answer(
                "⚠️ متأسفانه اطلاعات این تمرین یافت نشد.",
                reply_markup=get_back_to_main_keyboard(),
            )
            await state.clear()
            return

        target = content.get("target", "")
        note = content.get("note", "")

        note_text = f"\n\n💡 نکته: {note}" if note else ""
        await message.answer(
            "✅ ترجمه شما ثبت شد.\n\n"
            f"📝 ترجمه پیشنهادی:\n<b>{target}</b>{note_text}",
            reply_markup=get_back_to_main_keyboard(),
        )
    except Exception as e:
        logger.error(f"Error handling translation reply: {e}")
    finally:
        await state.clear()


