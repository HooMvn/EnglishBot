@router.callback_query(F.data.startswith("start_reading:"))
async def handle_start_reading(callback: CallbackQuery, state: FSMContext) -> None:
    """Present a reading passage with options to answer questions or summarize."""
    try:
        exercise_id = int(callback.data.split(":")[1])
        exercise = await db.get_exercise(exercise_id)

        if not exercise:
            await callback.answer("⚠️ تمرین یافت نشد.", show_alert=True)
            return

        if exercise.get("audio_file_id"):
            await bot.send_voice(
                chat_id=callback.message.chat.id, voice=exercise["audio_file_id"]
            )

        transcript = (
            exercise.get("transcript") or "⚠️ متنی برای این تمرین ثبت نشده است."
        )
        await callback.message.answer(transcript)

        builder = InlineKeyboardBuilder()
        questions = exercise.get("questions")
        if isinstance(questions, list) and questions:
            builder.row(
                InlineKeyboardButton(
                    text="📝 شروع سوالات",
                    callback_data=f"begin_questions:{exercise_id}",
                )
            )
        builder.row(
            InlineKeyboardButton(
                text="✍️ ارسال خلاصه من",
                callback_data=f"request_summary:{exercise_id}",
            )
        )

        await callback.message.answer(
            "چه کاری می‌خواهی انجام بدهی؟", reply_markup=builder.as_markup()
        )
        await callback.answer()
    except Exception as e:
        logger.error(f"Error starting reading exercise '{callback.data}': {e}")
        await callback.answer("⚠️ خطایی رخ داد.", show_alert=True)


@router.callback_query(F.data.startswith("request_summary:"))
async def handle_request_summary(callback: CallbackQuery, state: FSMContext) -> None:
    """Ask the user to write a short summary of the reading passage."""
    try:
        exercise_id = int(callback.data.split(":")[1])

        await state.set_state(ExerciseState.waiting_for_summary)
        await state.update_data(summary_exercise_id=exercise_id)

        await callback.message.answer("✍️ خلاصه این متن را در ۲-۳ جمله بنویس و بفرست:")
        await callback.answer()
    except Exception as e:
        logger.error(f"Error requesting summary '{callback.data}': {e}")
        await callback.answer("⚠️ خطایی رخ داد.", show_alert=True)


@router.message(ExerciseState.waiting_for_summary, F.text)
async def handle_summary_reply(message: Message, state: FSMContext) -> None:
    """Receive the user's summary and show a suggested sample summary."""
    try:
        data = await state.get_data()
        exercise_id = data.get("summary_exercise_id")
        exercise = await db.get_exercise(exercise_id) if exercise_id else None

        if not exercise:
            await message.answer(
                "⚠️ متأسفانه اطلاعات این تمرین یافت نشد.",
                reply_markup=get_back_to_main_keyboard(),
            )
            await state.clear()
            return

        # `grammar_notes` doubles as the sample-summary field for reading
        # exercises, to avoid adding a new schema column for this part.
        sample_summary = exercise.get("grammar_notes")
        sample_text = (
            f"\n\n📝 نمونه خلاصه پیشنهادی:\n{sample_summary}"
            if sample_summary
            else ""
        )

        builder = InlineKeyboardBuilder()
        questions = exercise.get("questions")
        if isinstance(questions, list) and questions:
            builder.row(
                InlineKeyboardButton(
                    text="📝 شروع سوالات",
                    callback_data=f"begin_questions:{exercise_id}",
                )
            )
        else:
            builder.row(
                InlineKeyboardButton(text="🏠 منوی اصلی", callback_data="back:main")
            )

        await message.answer(
            f"✅ خلاصه شما ثبت شد!{sample_text}", reply_markup=builder.as_markup()
        )
    except Exception as e:
        logger.error(f"Error handling summary reply: {e}")
    finally:
        await state.clear()
